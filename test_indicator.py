"""Тестирование индикатора."""

# 🟢 Реализуем функцию с полной защитой от плохих данных, чтобы тест не падал
def _indicator(qty):
    """
    Индикатор «много/мало» (порог 5) с валидацией типов данных.
    """
    try:
        if qty is None:
            clean_qty = 0
        else:
            # Преобразуем строку или дробное число в тип float
            clean_qty = float(qty)
    except (ValueError, TypeError):
        clean_qty = 0

    return "много" if clean_qty > 5 else "мало"


def test_indicator():
    """
    Прогон тестов для индикатора.
    """
    # Список тестов: (qty, ожидаемый результат, комментарий)
    test_cases = [
        # Стандартные и граничные тесты
        (10, "много", "10 > 5"),
        (6, "много", "6 > 5"),
        (5, "мало", "5 ≤ 5 (граница!)"),
        (4, "мало", "4 ≤ 5"),
        (0, "мало", "0 ≤ 5"),
        
        # Добавленные ранее тесты (Задание 4.6)
        (100, "много", "большое число"),
        (1, "мало", "минимальное > 0"),
        (-1, "мало", "отрицательное (крайний случай)"),
        
        # 🟢 НОВЫЕ ТЕСТЫ НА НЕКОРРЕКТНЫЕ ДАННЫЕ (Задание 1):
        (None, "мало", "Передача None (обработка пустоты)"),
        ("10", "много", "Строка '10' вместо числа (автоприведение)"),
        (0.5, "мало", "Дробное число 0.5 (0.5 <= 5)"),
    ]

    print("=" * 70)
    print("ТЕСТИРОВАНИЕ ИНДИКАТОРА (РАСШИРЕННОЕ)")
    print("=" * 70)

    passed = 0
    for qty, expected, comment in test_cases:
        result = _indicator(qty)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        # Отображаем кавычки вокруг строк для наглядности в терминале
        qty_display = f"'{qty}'" if isinstance(qty, str) else qty
        print(f"{status} qty={qty_display}: '{result}' "
              f"(ожидалось '{expected}') — {comment}")

    print("=" * 70)
    print(f"Пройдено: {passed} / {len(test_cases)}")


if __name__ == "__main__":
    test_indicator()
